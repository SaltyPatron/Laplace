    private static readonly Lazy<Dictionary<string, int>> SurfaceMap = new(BuildSurfaceMap);
    private static readonly Lazy<Hash128[]> TypeIdCache = new(BuildTypeIds);

    private static Dictionary<string, int> BuildSurfaceMap()
    {
        var map = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        for (int i = 0; i < Aliases.Length; i++) map.TryAdd(Aliases[i].Surface, i);
        return map;
    }

    private static Hash128[] BuildTypeIds()
    {
        var ids = new Hash128[Table.Length];
        for (int i = 0; i < Table.Length; i++) ids[i] = Hash128.Text(Table[i].Canonical);
        return ids;
    }

    public static int Count => Table.Length;
    public static string Canonical(int index) => Table[index].Canonical;
    public static bool IsRetired(int index) => Table[index].SuccessorIdx != -1;
    public static Hash128 CanonicalId(int index) => TypeIdCache.Value[index];

    public static bool TryResolveSurface(
        string surface, out Hash128 id, out double rank, out bool symmetric, out bool flip, out Hash128 parentId)
    {
        id = Hash128.Zero; rank = 0; symmetric = false; flip = false; parentId = Hash128.Zero;
        if (string.IsNullOrWhiteSpace(surface)) return false;
        string key = surface.Trim();
        int canonIdx = -1;
        if (SurfaceMap.Value.TryGetValue(key, out int aIdx)) { canonIdx = Aliases[aIdx].CanonicalIdx; flip = Aliases[aIdx].Flip; }
        else { for (int i = 0; i < Table.Length; i++) if (string.Equals(Table[i].Canonical, key, StringComparison.OrdinalIgnoreCase)) { canonIdx = i; break; } }
        if ((uint)canonIdx >= (uint)Table.Length) { id = Hash128.Text(key); return false; }
        var def = Table[canonIdx];
        id = TypeIdCache.Value[canonIdx];
        rank = def.Rank; symmetric = def.Symmetric;
        parentId = def.ParentIdx >= 0 ? TypeIdCache.Value[def.ParentIdx] : Hash128.Zero;
        return true;
    }
