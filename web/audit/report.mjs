// Merge static + live results into audit/STATUS.md. Missing result = NOT RUN (never counted as done).
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('.', import.meta.url));
const findings = JSON.parse(readFileSync(join(dir, 'findings.json'), 'utf8')).items;
const load = (f) => (existsSync(join(dir, 'results', f)) ? JSON.parse(readFileSync(join(dir, 'results', f), 'utf8')) : null);
const statics = load('static.json') ?? {};
const live = load('live.json');

const liveById = {};
function visit(suite) {
  for (const spec of suite.specs ?? []) {
    const id = spec.title.match(/^\[([A-Z]+-\d+)\]/)?.[1];
    if (!id) continue;
    const result = spec.tests?.[0]?.results?.at(-1);
    const msg = result?.error?.message?.split('\n').find((l) => l.trim()) ?? '';
    liveById[id] = { pass: result?.status === 'passed', detail: msg.replace(/\u001b\[[0-9;]*m/g, '').slice(0, 160) };
  }
  for (const child of suite.suites ?? []) visit(child);
}
if (live) for (const s of live.suites ?? []) visit(s);

const rows = findings.map((f) => {
  const r = f.kind === 'static' ? statics[f.id] : liveById[f.id];
  const state = r ? (r.pass ? 'DONE' : 'OPEN') : 'NOT RUN';
  const detail = r ? (f.kind === 'static' ? `value=${r.value}` : r.detail) : '';
  return { ...f, state, detail };
});
const done = rows.filter((r) => r.state === 'DONE').length;
const bySev = ['P0', 'P1', 'P2', 'P3'].map((s) => {
  const of = rows.filter((r) => r.sev === s);
  return `${s} ${of.filter((r) => r.state === 'DONE').length}/${of.length}`;
}).join(' · ');
const host = live?.config?.projects?.[0]?.use?.baseURL ?? process.env.LAPLACE_AUDIT_URL ?? 'n/a';

const md = [
  '# UI audit status',
  '',
  `Generated ${new Date().toISOString()} · host ${host} · **${done}/${rows.length} done** · ${bySev}`,
  '',
  'Generated by `npm run audit`. Do not edit by hand; an item is DONE only when its check passes.',
  '',
  '| ID | Sev | State | Title | Last result |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.sev} | ${r.state} | ${r.title} | ${r.detail.replace(/\|/g, '\\|')} |`),
  '',
].join('\n');
writeFileSync(join(dir, 'STATUS.md'), md);
console.log(`${done}/${rows.length} done · ${bySev}`);
